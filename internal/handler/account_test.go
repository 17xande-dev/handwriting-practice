func TestPasswordHashUpgradeDoesNotOverwriteNewerHash(t *testing.T) {
	s := newAccountServer(t)
	// Change the hash after verification but before the CAS, without relying
	// on concurrent goroutine scheduling or invalidating the new session.
	_, err := s.db.ExecContext(t.Context(), `CREATE TRIGGER change_hash_after_signin
		AFTER INSERT ON auth_sessions BEGIN
			UPDATE users SET password_hash = 'newer hash' WHERE id = NEW.user_id;
		END`)
	if err != nil {
		t.Fatal(err)
	}
	if u := s.signInLegacy(t, "form"); u.PasswordHash != "newer hash" {
		t.Fatal("password hash upgrade overwrote the newer hash")
	}
}

func TestPasswordHashUpgradeFailureDoesNotFailSignIn(t *testing.T) {
	s := newAccountServer(t)
	_, err := s.db.ExecContext(t.Context(), `CREATE TRIGGER reject_hash_upgrade
		BEFORE UPDATE OF password_hash ON users BEGIN
			SELECT RAISE(FAIL, 'test write failure');
		END`)
	if err != nil {
		t.Fatal(err)
	}
	if u := s.signInLegacy(t, "token"); u.PasswordHash != preMigrationHash {
		t.Fatal("failed write changed the legacy hash")
	}
}

func (s *testServer) signInLegacy(t *testing.T, via string) account.User {
	t.Helper()
	u, err := s.accounts.Create(t.Context(), "legacy@x.com", preMigrationHash, false)
	if err != nil {
		t.Fatal(err)
	}
	var token string
	if via == "token" {
		token = s.deviceToken(t, u.Email, testPassword)
	} else {
		token = s.signIn(t, u.Email, testPassword)
	}
	got, _, err := s.accounts.Authenticate(t.Context(), token)
	if err != nil || got.ID != u.ID {
		t.Fatalf("legacy sign-in did not create a working session: id=%d err=%v", got.ID, err)
	}
	return got
}

// The cookie signs in an account, so it must be unreadable to scripts and
// never sent on another site's cross-site POST.
func TestSessionCookieAttributes(t *testing.T) {
	s := newAccountServer(t)
	s.addUser(t, "a@x.com", false)
	srv := httptest.NewTLSServer(s.routes)
	t.Cleanup(srv.Close)
	browser := webtest.NewServer(t, srv)
	want := webtest.CookieWant{
		Name: "__Host-hp_session", Path: "/", Secure: true, HttpOnly: true, SameSite: http.SameSiteLaxMode,
	}
	login := browser.PostForm("/account/login", url.Values{"email": {"a@x.com"}, "password": {testPassword}})
	login.WantRedirect(http.StatusSeeOther, "/account")
	c := webtest.WantCookie(t, login, want)
	_, sess, err := s.accounts.Authenticate(t.Context(), c.Value)
	if err != nil {
		t.Fatal("cannot authenticate the issued token:", err)
	}
	maxAge := int((90 * 24 * time.Hour).Seconds())
	// Set floors the time between issuance and writing the cookie.
	if c.MaxAge > maxAge || c.MaxAge < maxAge-2 || !c.Expires.Equal(sess.CreatedAt.Add(90*24*time.Hour)) {
		t.Errorf("Max-Age=%d Expires=%v, want 90 days from creation", c.MaxAge, c.Expires)
	}
	logout := browser.PostForm("/account/logout", nil)
	logout.WantRedirect(http.StatusSeeOther, "/account?notice=signed-out")
	want.Cleared = true
	if c := webtest.WantCookie(t, logout, want); c.Value != "" || c.Expires.Unix() != 0 {
		t.Error("logout did not clear the cookie value and expire it")
	}
}

